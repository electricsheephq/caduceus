def test_jobs_return_results_or_keep_running():
    assert jobs.submit("fast", lambda: 42, wait_s=5) == {"state": "done", "result": 42}
    gate = threading.Event()
    started = jobs.submit("slow", lambda: gate.wait(5) and "finished", wait_s=0.05)
    assert started == {"state": "running"}
    assert jobs.submit("slow", lambda: None, wait_s=0)["state"] == "busy"
    gate.set()
    assert jobs.join("slow", timeout=5)
    failed = jobs.submit("boom", lambda: 1 / 0, wait_s=5)
    assert failed["state"] == "error" and "ZeroDivisionError" in failed["error"]


