def test_open_vault_is_idempotent(data_dir):
    first = open_vault(data_dir / "vault.db")
    first.close()
    second = open_vault(data_dir / "vault.db")
    tables = {r[0] for r in second.execute("SELECT name FROM sqlite_master WHERE type IN ('table','view')")}
    assert {"source_artifact", "import_run", "genotype_call", "annotation_snapshot", "search_doc"} <= tables
    assert second.execute("SELECT value FROM meta WHERE key='schema_version'").fetchone()[0] == "1"
    assert second.execute("SELECT count(*) FROM subject").fetchone()[0] == 1
    second.close()


def test_store_source_copies_once(vault, tmp_path):
    original = tmp_path / "genome export.txt"
    original.write_text("# synthetic\nrs1\t1\t100\tAA\n")
    first, existed = sources.store_source(vault, original, SourceKind.DTC)
    assert not existed
    stored = sources.source_file(vault, first)
    assert stored.read_text() == original.read_text()
    assert " " not in stored.name
    again, existed = sources.store_source(vault, original, SourceKind.DTC)
    assert existed and again.id == first.id
    assert vault.execute("SELECT count(*) FROM source_artifact").fetchone()[0] == 1


def test_import_runs_once_per_version_and_crashed_runs_resume(vault, tmp_path):
    path = tmp_path / "a.txt"
    path.write_text("x")
    src, _ = sources.store_source(vault, path, SourceKind.OTHER)
    crashed = sources.begin_import(vault, src, "dtc", "1")
    resumed = sources.begin_import(vault, src, "dtc", "1")  # the first run never finished
    assert resumed.id != crashed.id
    assert sources.run_info(vault, crashed.id)["status"] == "interrupted"
    sources.update_progress(vault, resumed.id, {"rows": 5})
    sources.finish_import(vault, resumed.id, counts={"rows": 5}, status="succeeded")
    assert sources.begin_import(vault, src, "dtc", "1") is None  # already imported: a no-op
    assert sources.begin_import(vault, src, "dtc", "2") is not None  # a new parser version re-imports
    info = sources.run_info(vault, resumed.id)
    assert info["counts"] == {"rows": 5} and info["progress"] == {"rows": 5}
    with pytest.raises(ValueError):
        sources.finish_import(vault, resumed.id, counts={}, status="running")


def test_sniff_kind(tmp_path):
    dtc = tmp_path / "genome.txt"
    dtc.write_text("# This data file generated by 23andMe at: x\n# rsid\tchromosome\tposition\tgenotype\n")
    assert sources.sniff_kind(dtc) == "dtc"
    zipped = tmp_path / "export.zip"
    with zipfile.ZipFile(zipped, "w") as zf:
        zf.writestr("apple_health_export/export.xml", "<HealthData/>")
    assert sources.sniff_kind(zipped) == "apple_health"
    report = tmp_path / "promethease.zip"
    with zipfile.ZipFile(report, "w") as zf:
        zf.writestr("promethease.html", "<html></html>")
    assert sources.sniff_kind(report) == "promethease"
    ancestry = tmp_path / "AncestryDNA.zip"
    with zipfile.ZipFile(ancestry, "w") as zf:
        zf.writestr("AncestryDNA.txt", "#AncestryDNA raw data download\nrsid\tchromosome\tposition\tallele1\tallele2\n")
    assert sources.sniff_kind(ancestry) == "dtc"
    other = tmp_path / "notes.txt"
    other.write_text("hello")
    assert sources.sniff_kind(other) == "other"


def _index(vault, kind, ref, title, body, category):
    with write_txn(vault):
        search.index_doc(vault, kind=kind, ref=ref, title=title, body=body, category=category)


def test_search_ranks_filters_and_withholds(vault):
    _index(vault, "annotation", "1", "rs4149056 SLCO1B1", "Simvastatin myopathy risk is higher", Category.PGX)
    _index(vault, "annotation", "2", "rs429358 APOE", "Alzheimer's disease risk allele", Category.ALZHEIMERS)
    _index(vault, "research", "3", "Statin study", "New simvastatin trial results", Category.RESEARCH)
    open_hits = search.search(vault, "simvastatin", policy=Policy())
    assert [r["ref"] for r in open_hits["results"]][:2] and open_hits["withheld"] == 0
    assert search.search(vault, "alzheimer", policy=Policy())["results"]
    standard = Policy(level="standard")
    hidden = search.search(vault, "alzheimer", policy=standard)
    assert hidden["results"] == [] and hidden["withheld"] == 1
    unlocked = Policy(level="standard", unlocked=frozenset({Category.ALZHEIMERS}))
    assert search.search(vault, "alzheimer", policy=unlocked)["results"]
    kinds = search.search(vault, "simvastatin", policy=Policy(), kinds=["research"])
    assert [r["kind"] for r in kinds["results"]] == ["research"]
    assert search.search(vault, "simvastatin unicorn", policy=Policy())["match"] == "any_term"
    assert search.fetch(vault, "annotation:2", policy=standard)["withheld"] is True
    assert search.fetch(vault, "annotation:1", policy=Policy())["body"].startswith("Simvastatin")


def test_reindex_replaces_and_fts_syntax_is_inert(vault):
    _index(vault, "journal", "1", "Old title", "old body", Category.WELLNESS)
    _index(vault, "journal", "1", "New title", "fresh body", Category.WELLNESS)
    assert vault.execute("SELECT count(*) FROM search_doc").fetchone()[0] == 1
    assert search.search(vault, "fresh", policy=Policy())["results"]
    assert not search.search(vault, "old", policy=Policy())["results"]
    for nasty in ('"', 'AND OR NOT', "body:*", "NEAR(a b)", "(((", "-", ""):
        search.search(vault, nasty, policy=Policy())  # never raises
    with pytest.raises(ValueError):
        _index(vault, "nonsense", "1", "t", "b", Category.GENERAL)


def test_policy_fails_closed():
    assert Policy.from_settings(lambda k, d: d).level == "open"
    bad_level = Policy.from_settings(lambda k, d: "everything" if k == "privacy_level" else d)
    assert bad_level.level == "standard" and bad_level.errors
    malformed = Policy.from_settings(lambda k, d: {"x": 1} if k == "hidden_categories" else d)
    assert malformed.level == "standard"
    hidden = Policy.from_settings(lambda k, d: ["pgx", "bogus"] if k == "hidden_categories" else d)
    assert not allowed(hidden, Category.PGX) and allowed(hidden, Category.TRAIT)
    assert any("bogus" in e for e in hidden.errors)
    assert not allowed(Policy(), "not-a-category")
    assert allowed(Policy(), Category.CARRIER)
    assert not allowed(Policy(level="standard"), Category.CARRIER)


