"""Deterministic, entirely synthetic DTC exports; no real report content."""
import random
import zipfile
from contextlib import contextmanager
from io import TextIOWrapper
from pathlib import Path


@contextmanager
def _output(path, zipped, crlf, member):
    if zipped:
        with zipfile.ZipFile(path, "w", compression=zipfile.ZIP_DEFLATED) as archive:
            info = zipfile.ZipInfo(member, date_time=(2020, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            with archive.open(info, "w") as raw:
                with TextIOWrapper(raw, encoding="utf-8", newline="\r\n" if crlf else "\n") as text:
                    yield text
    else:
        with open(path, "w", encoding="utf-8", newline="\r\n" if crlf else "\n") as text:
            yield text


def _rows(n, inject, seed):
    rng = random.Random(seed)
    extra = dict(inject or {})
    for i in range(1, n + 1):
        marker = f"rs{i}"
        generated = rng.choice("ACGT") + rng.choice("ACGT")
        yield marker, i, extra.pop(marker, generated)
    for i, (marker, genotype) in enumerate(sorted(extra.items()), n + 1):
        yield marker, i, genotype


def make_23andme(path, version="v5", n=100, inject=None, crlf=False, zip=False, seed=0, *, build="37"):
    path = Path(path)
    version = "v" + str(version).removeprefix("v")
    with _output(path, zip, crlf, f"synthetic_{version}_genome.txt") as text:
        text.write("# Synthetic data generated by 23andMe format generator\n")
        text.write(f"# reference human assembly build {build}\n")
        text.write("# rsid\tchromosome\tposition\tgenotype\n")
        chroms = [str(i) for i in range(1, 23)] + ["X", "Y", "MT"]
        for marker, i, gt in _rows(n, inject, seed):
            text.write(f"{marker}\t{chroms[(i - 1) % len(chroms)]}\t{1000 + i}\t{gt}\n")
    return path


def make_ancestry(path, n=100, inject=None, crlf=False, zip=False, seed=0, *, build="37"):
    path = Path(path)
    with _output(path, zip, crlf, "synthetic_ancestry.txt") as text:
        text.write("# Synthetic AncestryDNA format data\n")
        text.write(f"# reference human assembly build {build}\n")
        text.write("rsid\tchromosome\tposition\tallele1\tallele2\n")
        for marker, i, gt in _rows(n, inject, seed):
            first, second = ("0", "0") if gt == "--" else (gt[0], gt[-1])
            text.write(f"{marker}\t{(i - 1) % 26 + 1}\t{1000 + i}\t{first}\t{second}\n")
    return path
